#requires -Version 3.0
param(
    [Parameter(Mandatory = $true)]
    [string[]] $InputFiles,

    [Parameter(Mandatory = $true)]
    [string] $OutputFile,

    [string] $Name = 'Merged PAL Threshold File',
    [string] $Description = 'Merged PAL threshold file generated by PalMergeThresholdFiles.ps1',
    [string] $ContentOwners = 'PAL Community',
    [string] $FeedbackEmailAddress,
    [string] $Version = '1.0',
    [string] $PalVersion = '2.0',
    [string] $Language = 'English',
    [string] $LanguageCode = 'en',

    [switch] $NoResolveInheritance
)

Set-StrictMode -Version 3
$Error.Clear()

#// PAL Threshold Merger
#// Merges multiple PAL threshold XML files into a single standalone file.
#// Dedup rules:
#//   QUESTION: unique by QUESTIONVARNAME (first one wins)
#//   ANALYSIS: unique by ID when available, otherwise by NAME (first one wins)

Function Test-Property {
    param(
        [Parameter(Position = 0, Mandatory = $true)] $InputObject,
        [Parameter(Position = 1, Mandatory = $true)] [string] $Name
    )

    [bool] (Get-Member -InputObject $InputObject -Name $Name -MemberType *Property)
}

Function Resolve-ThresholdPath {
    param(
        [Parameter(Mandatory = $true)] [string] $Path,
        [Parameter(Mandatory = $true)] [string] $BaseDirectory
    )

    if ([System.IO.Path]::IsPathRooted($Path)) {
        return [System.IO.Path]::GetFullPath($Path)
    }

    return [System.IO.Path]::GetFullPath((Join-Path -Path $BaseDirectory -ChildPath $Path))
}

Function Read-ThresholdXml {
    param(
        [Parameter(Mandatory = $true)] [string] $FilePath
    )

    if (-not (Test-Path -LiteralPath $FilePath)) {
        throw "Threshold file not found: $FilePath"
    }

    try {
        [xml] (Get-Content -LiteralPath $FilePath -Encoding UTF8)
    }
    catch {
        throw "Failed to parse XML file '$FilePath'. $_"
    }
}

Function Get-ThresholdLoadOrder {
    param(
        [Parameter(Mandatory = $true)] [string] $FilePath,
        [Parameter(Mandatory = $true)] $Visited,
        [Parameter(Mandatory = $true)] $OrderedFiles,
        [Parameter(Mandatory = $true)] [bool] $ResolveInheritance
    )

    $normalizedPath = [System.IO.Path]::GetFullPath($FilePath)
    if ($Visited.Contains($normalizedPath)) {
        return
    }

    [void] $Visited.Add($normalizedPath)
    [void] $OrderedFiles.Add($normalizedPath)

    if (-not $ResolveInheritance) {
        return
    }

    $xml = Read-ThresholdXml -FilePath $normalizedPath
    $baseDirectory = Split-Path -Path $normalizedPath -Parent

    foreach ($inheritanceNode in $xml.SelectNodes('//INHERITANCE')) {
        if (-not (Test-Property -InputObject $inheritanceNode -Name 'FILEPATH')) {
            continue
        }

        $inheritPath = [string] $inheritanceNode.FILEPATH
        if ([string]::IsNullOrWhiteSpace($inheritPath)) {
            continue
        }

        $resolvedInheritancePath = Resolve-ThresholdPath -Path $inheritPath -BaseDirectory $baseDirectory
        Get-ThresholdLoadOrder -FilePath $resolvedInheritancePath -Visited $Visited -OrderedFiles $OrderedFiles -ResolveInheritance $ResolveInheritance
    }
}

Function New-MergedPalDocument {
    param(
        [Parameter(Mandatory = $true)] [string] $Name,
        [Parameter(Mandatory = $true)] [string] $Description,
        [Parameter(Mandatory = $true)] [string] $ContentOwners,
        [Parameter(Mandatory = $true)] [string] $FeedbackEmailAddress,
        [Parameter(Mandatory = $true)] [string] $Version,
        [Parameter(Mandatory = $true)] [string] $PalVersion,
        [Parameter(Mandatory = $true)] [string] $Language,
        [Parameter(Mandatory = $true)] [string] $LanguageCode
    )

    $doc = New-Object System.Xml.XmlDocument
    $decl = $doc.CreateXmlDeclaration('1.0', 'utf-8', $null)
    [void] $doc.AppendChild($decl)

    $root = $doc.CreateElement('PAL')
    $root.SetAttribute('PALVERSION', $PalVersion)
    $root.SetAttribute('NAME', $Name)
    $root.SetAttribute('DESCRIPTION', $Description)
    $root.SetAttribute('CONTENTOWNERS', $ContentOwners)
    $root.SetAttribute('FEEDBACKEMAILADDRESS', $FeedbackEmailAddress)
    $root.SetAttribute('VERSION', $Version)
    $root.SetAttribute('LANGUAGE', $Language)
    $root.SetAttribute('LANGUAGECODE', $LanguageCode)
    [void] $doc.AppendChild($root)

    return $doc
}

Function Get-AnalysisKey {
    param([Parameter(Mandatory = $true)] $AnalysisNode)

    $idValue = ''
    if (Test-Property -InputObject $AnalysisNode -Name 'ID') {
        $idValue = [string] $AnalysisNode.ID
    }

    if (-not [string]::IsNullOrWhiteSpace($idValue)) {
        return "ID::$($idValue.ToLowerInvariant())"
    }

    $nameValue = ''
    if (Test-Property -InputObject $AnalysisNode -Name 'NAME') {
        $nameValue = [string] $AnalysisNode.NAME
    }

    if (-not [string]::IsNullOrWhiteSpace($nameValue)) {
        return "NAME::$($nameValue.ToLowerInvariant())"
    }

    throw 'ANALYSIS node is missing both ID and NAME attributes.'
}

Function Save-XmlUtf8 {
    param(
        [Parameter(Mandatory = $true)] [System.Xml.XmlDocument] $Document,
        [Parameter(Mandatory = $true)] [string] $FilePath
    )

    $settings = New-Object System.Xml.XmlWriterSettings
    $settings.Indent = $true
    $settings.IndentChars = '  '
    $settings.NewLineChars = "`r`n"
    $settings.NewLineHandling = [System.Xml.NewLineHandling]::Replace
    $settings.Encoding = New-Object System.Text.UTF8Encoding($false)

    $dir = Split-Path -Path $FilePath -Parent
    if (-not [string]::IsNullOrWhiteSpace($dir) -and -not (Test-Path -LiteralPath $dir)) {
        [void] (New-Item -Path $dir -ItemType Directory -Force)
    }

    $writer = [System.Xml.XmlWriter]::Create($FilePath, $settings)
    try {
        $Document.Save($writer)
    }
    finally {
        $writer.Dispose()
    }
}

#//////////
#// Main //
#//////////

$scriptDirectory = Split-Path -Parent $MyInvocation.MyCommand.Path
$orderedFiles = New-Object System.Collections.ArrayList
$visited = New-Object 'System.Collections.Generic.HashSet[string]'

foreach ($inputPath in $InputFiles) {
    $resolvedInput = Resolve-ThresholdPath -Path $inputPath -BaseDirectory (Get-Location).Path
    Get-ThresholdLoadOrder -FilePath $resolvedInput -Visited $visited -OrderedFiles $orderedFiles -ResolveInheritance (-not $NoResolveInheritance)
}

if ($orderedFiles.Count -eq 0) {
    throw 'No threshold files were resolved from the provided InputFiles.'
}

$sourceXmlDocs = @()
foreach ($file in $orderedFiles) {
    $sourceXmlDocs += Read-ThresholdXml -FilePath $file
}

#// If FeedbackEmailAddress not provided, inherit from the first source file.
if ([string]::IsNullOrWhiteSpace($FeedbackEmailAddress)) {
    $firstRoot = $sourceXmlDocs[0].PAL
    if ($firstRoot -and (Test-Property -InputObject $firstRoot -Name 'FEEDBACKEMAILADDRESS') -and -not [string]::IsNullOrWhiteSpace([string]$firstRoot.FEEDBACKEMAILADDRESS)) {
        $FeedbackEmailAddress = [string] $firstRoot.FEEDBACKEMAILADDRESS
    }
    else {
        $FeedbackEmailAddress = 'pal@contoso.com'
    }
}

$mergedDoc = New-MergedPalDocument -Name $Name -Description $Description -ContentOwners $ContentOwners -FeedbackEmailAddress $FeedbackEmailAddress -Version $Version -PalVersion $PalVersion -Language $Language -LanguageCode $LanguageCode

$questionKeys = @{}
$analysisKeys = @{}
[int] $questionCountAdded = 0
[int] $analysisCountAdded = 0
[int] $questionCountSkipped = 0
[int] $analysisCountSkipped = 0

foreach ($srcDoc in $sourceXmlDocs) {
    foreach ($qNode in $srcDoc.SelectNodes('//QUESTION')) {
        if (-not (Test-Property -InputObject $qNode -Name 'QUESTIONVARNAME')) {
            continue
        }

        $qKey = [string] $qNode.QUESTIONVARNAME
        if ([string]::IsNullOrWhiteSpace($qKey)) {
            continue
        }

        $qKey = $qKey.ToLowerInvariant()
        if ($questionKeys.ContainsKey($qKey)) {
            $questionCountSkipped++
            continue
        }

        $importedQuestion = $mergedDoc.ImportNode($qNode, $true)
        [void] $mergedDoc.PAL.AppendChild($importedQuestion)
        $questionKeys[$qKey] = $true
        $questionCountAdded++
    }

    foreach ($aNode in $srcDoc.SelectNodes('//ANALYSIS')) {
        $aKey = Get-AnalysisKey -AnalysisNode $aNode
        if ($analysisKeys.ContainsKey($aKey)) {
            $analysisCountSkipped++
            continue
        }

        $importedAnalysis = $mergedDoc.ImportNode($aNode, $true)
        [void] $mergedDoc.PAL.AppendChild($importedAnalysis)
        $analysisKeys[$aKey] = $true
        $analysisCountAdded++
    }
}

$outputResolved = Resolve-ThresholdPath -Path $OutputFile -BaseDirectory (Get-Location).Path
Save-XmlUtf8 -Document $mergedDoc -FilePath $outputResolved

Write-Host ""
Write-Host "PAL Threshold Merge Complete"
Write-Host "  Output File: $outputResolved"
Write-Host "  Source Files Loaded: $($orderedFiles.Count)"
Write-Host "  Questions Added: $questionCountAdded (Skipped Duplicates: $questionCountSkipped)"
Write-Host "  Analyses Added: $analysisCountAdded (Skipped Duplicates: $analysisCountSkipped)"
Write-Host ""
Write-Host "Source files in merge order:"
$orderedFiles | ForEach-Object { Write-Host "  - $_" }
